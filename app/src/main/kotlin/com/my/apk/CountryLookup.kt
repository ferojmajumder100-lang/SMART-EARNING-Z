    data class CountryInfo(val name: String, val iso: String) {
        val flag: String get() = isoToFlag(iso)
        val nameWithIso: String get() = "$name-$iso"
        val displayLabel: String get() = "$flag $name-$iso"
    }

    private val UNKNOWN = CountryInfo("Unknown", "UN")

    fun isoToFlag(iso: String): String {
        val code = iso.trim().uppercase()
        if (code.length != 2 || code == "UN") return "🌐"
        val c1 = code[0]
        val c2 = code[1]
        if (c1 !in 'A'..'Z' || c2 !in 'A'..'Z') return "🌐"
        val cp1 = 0x1F1E6 + (c1 - 'A')
        val cp2 = 0x1F1E6 + (c2 - 'A')
        return String(Character.toChars(cp1)) + String(Character.toChars(cp2))
    }

    fun lookup(rangeOrNumber: String): CountryInfo {
        var cleaned = rangeOrNumber.trim()
        if (cleaned.startsWith("+")) cleaned = cleaned.substring(1)
        if (cleaned.startsWith("00") && cleaned.length > 4) cleaned = cleaned.substring(2)

        val digits = buildString {
            for (ch in cleaned) {
                if (ch.isDigit()) append(ch)
                else if (ch == 'X' || ch == 'x' || ch == '*') break
            }
        }
        if (digits.isEmpty()) return UNKNOWN

        val maxLen = minOf(digits.length, 7)
        for (len in maxLen downTo 1) {
            val prefix = digits.substring(0, len)
            PREFIX_MAP[prefix]?.let { return it }
        }
        return UNKNOWN
    }

    fun formatLabel(rangeOrNumber: String): String = lookup(rangeOrNumber).displayLabel

